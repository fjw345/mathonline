-- Supabase/PostgreSQL baseline matching the local import database.
create table if not exists problem_sources (
  id text primary key, path text not null unique, filename text not null,
  source_kind text not null, included boolean not null,
  exclusion_reason text, sha256 text not null, page_count integer,
  text_page_count integer, rights_status text not null default 'needs_verification',
  created_at timestamptz not null default now()
);
create table if not exists problems (
  id text primary key, source_id text not null references problem_sources(id),
  external_id text not null unique, question_number integer not null,
  question_type text not null default 'unknown', content_markdown text not null,
  options_json jsonb, source_page_start integer not null, source_page_end integer not null,
  difficulty smallint not null check (difficulty between 1 and 5),
  status text not null default 'draft' check (status in ('draft','published','archived')),
  extraction_method text not null, requires_review boolean not null default true,
  answer_version integer not null default 1, created_at timestamptz not null default now()
);
create table if not exists problem_answers (
  problem_id text primary key references problems(id) on delete cascade,
  standard_answer text, grading_config_json jsonb,
  explanation_markdown text, explanation_source text not null default 'source_or_unavailable',
  verified boolean not null default false
);
create table if not exists tags (
  id bigint generated by default as identity primary key,
  dimension text not null, name text not null, unique (dimension,name)
);
create table if not exists problem_tags (
  problem_id text not null references problems(id) on delete cascade,
  tag_id bigint not null references tags(id) on delete cascade,
  primary key (problem_id,tag_id)
);
create table if not exists problem_source_links (
  problem_id text not null references problems(id) on delete cascade,
  source_id text not null references problem_sources(id), source_page_start integer not null,
  source_page_end integer not null, source_question_number integer not null,
  extraction_method text not null, is_primary boolean not null default false,
  primary key (problem_id,source_id,source_page_start,source_question_number)
);
create table if not exists problem_aliases (
  alias_problem_id text primary key,
  canonical_problem_id text not null references problems(id) on delete cascade,
  match_type text not null, similarity double precision not null,
  alias_content_markdown text, alias_answer_json jsonb
);
create table if not exists dedup_review_candidates (
  problem_id_a text not null references problems(id) on delete cascade,
  problem_id_b text not null references problems(id) on delete cascade,
  similarity double precision not null, primary key(problem_id_a,problem_id_b)
);
create index if not exists idx_problems_source on problems(source_id);
create index if not exists idx_problems_filter on problems(status,difficulty,question_type);
create index if not exists idx_problem_tags_tag on problem_tags(tag_id);
